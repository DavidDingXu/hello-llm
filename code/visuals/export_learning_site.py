"""将已生成的双语学习站导出为纯静态目录；请先运行 build_reading.py。本工具不发布。"""
import argparse
import json
from html.parser import HTMLParser
import os
from pathlib import Path
import re
import shutil
import tempfile
from urllib.parse import unquote, urlsplit


COLUMN = Path(__file__).resolve().parents[2]
MARKER = '.learning-site-export'
MARKER_TEXT = 'Generated by visuals/export_learning_site.py; re-export replaces this directory.\n'
PAGE_NAMES = {'index.html', 'index.en.html'}
ARTICLE_NAMES = PAGE_NAMES | {'README.md', 'README.en.md'} | {
    name + suffix + '.html'
    for name in ('walkthrough', 'lab3d', 'model-inspector', 'training-replay') for suffix in ('', '.en')
}
SITE_FILES = {'site.css', 'site.js', 'search-index.js', 'search-index.en.js',
              'python-lab.mjs', 'python-worker.mjs', 'python-modules.json', 'code-editor.mjs', 'code-editor.css',
              'training-lab.mjs','training-worker.mjs','training-engine.mjs',
              'tensor3d.js', 'tensor3d-LICENSE.txt', 'experiment-ui.css', 'experiment-ui.js',
              'experiment-special.css', 'experiment-special.js', 'model3d.js', 'rope3d.js',
              'embedding3d.js', 'surface3d.js'}
TRAINING_FILES = {'model.json','data.json','initial.f32','pretrained.f32','train-step.onnx','evaluate.onnx'}
# Readable references linked by the 3D labs; no Python execution is required.
EXPERIMENT_SOURCES = {
    'code/artifacts/lessons/l07.json',
    'code/artifacts/lessons/l13.json',
    'code/artifacts/first_run/forward_trace.json',
    'code/tiny_lm/rope.py',
    'code/tiny_lm/model.py',
}
MEDIA_SUFFIXES = {'.png', '.jpg', '.jpeg', '.svg', '.gif', '.webp', '.avif',
                  '.mp4', '.webm', '.mp3', '.wav', '.ogg'}
VIDEO_SUFFIXES = {'.mp4', '.webm', '.vtt', '.srt', '.png', '.jpg'}


def css_references(text):
    references = re.findall(r'url\(\s*[\'"]?([^\'"\)]+)[\'"]?\s*\)', text, re.I)
    references += re.findall(r'@import\s+[\'"]([^\'"]+)[\'"]', text, re.I)
    return [value.strip() for value in references]


def script_references(text):
    """仅收集实际加载调用；内嵌实验数据中的 figure/artifacts 来源字段不属于请求。"""
    references = []
    for pattern in (
        r'\b(?:fetch|import)\s*\(\s*([\'"])([^\'"\n]+)\1',
        r'\bnew\s+URL\s*\(\s*([\'"])([^\'"\n]+)\1',
        r'\.(?:src|href)\s*=\s*([\'"])([^\'"\n]+)\1',
        r'\bimport\s+[^;\n]*?\s+from\s*([\'"])([^\'"\n]+)\1',
    ):
        references.extend(value for _, value in re.findall(pattern, text))
    return references


class ResourceReferences(HTMLParser):
    def __init__(self):
        super().__init__()
        self.references = []
        self.script = self.style = False

    def handle_starttag(self, tag, attributes):
        attrs = dict(attributes)
        for name in ('href', 'src', 'poster', 'xlink:href', 'srcset', 'data-offline-href'):
            if attrs.get(name):
                self.references.append(attrs[name])
        if attrs.get('style'):
            self.references.extend(css_references(attrs['style']))
        if tag == 'script':
            self.script = attrs.get('type', '') in ('', 'module', 'text/javascript', 'application/javascript')
        if tag == 'style':
            self.style = True

    def handle_endtag(self, tag):
        if tag == 'script':
            self.script = False
        if tag == 'style':
            self.style = False

    def handle_data(self, text):
        if self.script:
            self.references.extend(script_references(text))
        if self.style:
            self.references.extend(css_references(text))


def allowed_resource(relative):
    parts = relative.parts
    if relative.as_posix() in EXPERIMENT_SOURCES:
        return True
    if len(parts) == 1:
        return parts[0] in PAGE_NAMES | {'index.html', 'index.en.html'}
    if parts[0] == 'course':
        return len(parts) == 2 and bool(re.fullmatch(r'(?:intro|end|\d{2})(?:\.en)?\.html', parts[1]))
    if relative.as_posix() in ('assets/brand.png', 'code/assets/wechat-official-account.jpg', 'assets/social-preview.png', 'assets/brand-mark.png', 'assets/favicon.png'):
        return True
    if parts[0] == 'dist':
        return len(parts) == 3 and relative.suffix in {'.pdf', '.epub'}
    if parts[:2] == ('assets', 'videos'):
        # 只沿页面实际的 src / poster / track src 收集，制作中及未引用视频不会被遍历。
        return relative.suffix.lower() in VIDEO_SUFFIXES
    if parts[:3] == ('code', 'visuals', 'reading_site'):
        if len(parts) == 5 and parts[3] == 'training':
            return parts[4] in TRAINING_FILES
        return len(parts) == 4 and parts[3] in SITE_FILES
    if parts[0] == 'chapters':
        if len(parts) == 3:
            return parts[2] in ARTICLE_NAMES
        return len(parts) >= 4 and parts[2] == 'images' and relative.suffix.lower() in MEDIA_SUFFIXES
    return False


def local_reference(reference, document, source):
    parsed = urlsplit(reference.strip())
    if parsed.scheme or parsed.netloc or not parsed.path:
        return None
    path = unquote(parsed.path)
    if path.startswith('/') or '\\' in path or '\x00' in path:
        raise ValueError(f'资源 URL 不支持项目子路径部署：{document.relative_to(source)} → {reference}')
    target = Path(os.path.abspath(document.parent / path))
    if not target.is_relative_to(source) or not target.resolve().is_relative_to(source):
        raise ValueError(f'资源越出学习站源目录：{document.relative_to(source)} → {reference}')
    return target


def collect_files(source=COLUMN):
    """从两种语言的首页沿运行时引用遍历；下载的 Markdown 作为原文件保留。"""
    source = Path(source).resolve()
    pending = [source / name for name in sorted(PAGE_NAMES)]
    files = set()
    while pending:
        path = pending.pop()
        if path in files:
            continue
        relative = path.relative_to(source)
        if not allowed_resource(relative):
            raise ValueError(f'链接指向学习站运行范围之外的文件：{relative.as_posix()}')
        if not path.is_file():
            raise FileNotFoundError(f'学习站资源缺失：{relative.as_posix()}')
        files.add(path)
        references = []
        if path.suffix in ('.html', '.svg'):
            parser = ResourceReferences()
            parser.feed(path.read_text(encoding='utf-8'))
            references = parser.references
        elif path.suffix == '.css':
            references = css_references(path.read_text(encoding='utf-8'))
        elif path.suffix in ('.js', '.mjs'):
            references = script_references(path.read_text(encoding='utf-8'))
        elif path.name == 'model.json' and path.parent.name == 'training':
            references = list(json.loads(path.read_text(encoding='utf-8'))['files'])
        for reference in references:
            target = local_reference(reference, path, source)
            if target is not None and target not in files:
                pending.append(target)
    return files


def export(target, *, source=COLUMN):
    source = Path(source).resolve()
    target = Path(target).expanduser()
    if target.is_symlink():
        raise ValueError('导出目录不能是符号链接')
    target = target.resolve()
    if source.is_relative_to(target):
        raise ValueError('不能覆盖学习站源目录或它的父目录')
    marker = target / MARKER
    if target.exists() and (
        not target.is_dir() or marker.is_symlink() or not marker.is_file()
        or marker.read_text(encoding='utf-8') != MARKER_TEXT
    ):
        raise ValueError(f'已有目录不属于本工具，拒绝覆盖：{target}')

    files = collect_files(source)
    target.parent.mkdir(parents=True, exist_ok=True)
    # 完整复制成功后才替换旧目录；缺件或复制失败不会破坏上一份导出。
    with tempfile.TemporaryDirectory(prefix='.learning-site-', dir=target.parent) as directory:
        staging = Path(directory) / 'next'
        staging.mkdir()
        for path in sorted(files):
            destination = staging / path.relative_to(source)
            destination.parent.mkdir(parents=True, exist_ok=True)
            shutil.copy2(path, destination)
        # 发行包独立传播时也保留软件、内容许可和署名要求。
        for name in ('LICENSE', 'LICENSE-CONTENT', 'NOTICE', 'LICENSING.md'):
            origin = source / name
            if not origin.is_file():
                origin = source / 'code' / name
            if origin.is_file():
                shutil.copy2(origin, staging / name)
        homepage, index = staging / 'index.html', staging / 'index.html'
        if homepage != index:
            shutil.copy2(homepage, index)
        (staging / '.nojekyll').write_text('', encoding='utf-8')
        (staging / MARKER).write_text(MARKER_TEXT, encoding='utf-8', newline='\n')
        exported = [path for path in staging.rglob('*') if path.is_file()]
        result = {'output': str(target), 'files': len(exported),
                  'bytes': sum(path.stat().st_size for path in exported)}
        previous = Path(directory) / 'previous'
        if target.exists():
            target.rename(previous)
        try:
            staging.rename(target)
        except OSError:
            if previous.exists():
                previous.rename(target)
            raise
    return result


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--out', required=True, type=Path, help='本地静态导出目录；重复导出会替换本工具的旧结果')
    args = parser.parse_args()
    try:
        result = export(args.out)
    except (OSError, ValueError) as error:
        parser.exit(1, f'导出失败：{error}\n')
    print(f"已导出 {result['files']} 个文件，{result['bytes'] / (1024 * 1024):.2f} MiB：{result['output']}")
